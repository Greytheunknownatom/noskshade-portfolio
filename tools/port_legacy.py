#!/usr/bin/env python3
"""Port the old single-file site's pages into Next.js, keeping markup and behaviour identical.

- The old Component class (state + renderVals + effects) becomes src/legacy/vm.js, run by LegacyShell.
- Each page section of the old template becomes a JSX component in src/legacy/sections/.
- Each route gets a tiny client wrapper in src/legacy/pages/.
Run: python3 tools/port_legacy.py <old index.html>
LEARN (lesson 7): a migration script. It's run once; after that the generated files are normal code.
"""
import json, os, re, subprocess, sys

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = open(SRC, encoding='utf-8').read().split('\n')
L = lambda a, b: '\n'.join(lines[a - 1:b])

def find(pat, start=1):
    for i in range(start - 1, len(lines)):
        if re.search(pat, lines[i]):
            return i + 1
    raise SystemExit('not found: ' + pat)

SECTIONS = [  # (component, gate value, page id)
    ('Home', 'isHome', 'home'), ('Work', 'isWork', 'work'), ('CaseKoynxAdmin', 'isCaseKA', 'case-koynx-admin'),
    ('CaseKoynx', 'isCase1', 'case-koynx'), ('CaseHillcross', 'isCaseHC', 'case-hillcross'), ('CasePortal', 'isCasePortal', 'case-hcportal'),
    ('CaseStudent', 'isCaseHCS', 'case-hcstudent'), ('CaseTeacher', 'isCaseHCT', 'case-hcteacher'), ('CaseLucenture', 'isCaseLC', 'case-lucenture'),
    ('CaseBlissbill', 'isCaseBB', 'case-blissbill'), ('CaseWemove', 'isCaseWM', 'case-wemove'), ('CaseLaundromate', 'isCaseLM', 'case-laundromate'),
    ('CaseHeatbud', 'isCaseHB', 'case-heatbud'), ('About', 'isAbout', 'about'), ('Contact', 'isContact', 'contact'),
]

def section_range(gate):
    a = find(r'^  <sc-if value="\{\{ ' + gate + r' \}\}"')
    depth, i = 0, a
    while True:
        ln = lines[i - 1]
        depth += len(re.findall(r'<sc-if\b', ln)) - len(re.findall(r'</sc-if>', ln))
        if depth == 0:
            return a, i
        i += 1

def convert(a, b):
    r = subprocess.run(['python3', os.path.join(ROOT, 'tools/dc2jsx.py'), SRC, str(a), str(b)], capture_output=True, text=True, check=True)
    hover = [l for l in r.stderr.splitlines() if l.startswith('.hv')]
    return r.stdout, hover

def rootify(code):
    # Asset paths must start at the site root, or /work/koynx would look for /work/assets/...
    return re.sub(r'''(["'(`])assets/''', r'\1/assets/', code)

def linkify(jsx):
    r = subprocess.run(['python3', os.path.join(ROOT, 'tools/linkify.py'), '/dev/stdin'], input=jsx, capture_output=True, text=True, check=True)
    return r.stdout

out_sections = os.path.join(ROOT, 'src/legacy/sections')
out_pages = os.path.join(ROOT, 'src/legacy/pages')
os.makedirs(out_sections, exist_ok=True); os.makedirs(out_pages, exist_ok=True)
all_hover = set()

HEAD = "// Generated by tools/port_legacy.py from the original site. Edit freely; it won't be regenerated.\n/* eslint-disable */\n// @ts-nocheck\nimport React from 'react';\nimport Link from 'next/link';\n\n"

for comp, gate, page in SECTIONS:
    a, b = section_range(gate)
    jsx, hov = convert(a, b)
    all_hover.update(hov)
    jsx = rootify(linkify(jsx))
    open(os.path.join(out_sections, comp + '.jsx'), 'w').write(HEAD + f"export default function {comp}({{ v }}) {{\n  return (\n    <>\n{jsx}\n    </>\n  );\n}}\n")
    open(os.path.join(out_pages, comp + '.tsx'), 'w').write(
        "'use client';\nimport LegacyShell from '../LegacyShell';\n"
        f"import Section from '../sections/{comp}';\n\n"
        f"export default function {comp}Page() {{\n  return <LegacyShell page=\"{page}\">{{(v) => <Section v={{v}} />}}</LegacyShell>;\n}}\n")

# Shared chrome: case-study storyline + top progress bar, and the overlays (experience modal, email, lightbox)
chrome_a = find(r'<!-- Scroll progress -->'); chrome_b = find(r'^  </div>$', chrome_a)
ov_a = find(r'<!-- Experience story modal -->'); ov_b = find(r'^</x-dc>') - 3
for name, (a, b) in {'Chrome': (chrome_a, chrome_b), 'Overlays': (ov_a, ov_b)}.items():
    jsx, hov = convert(a, b); all_hover.update(hov); jsx = rootify(jsx)
    open(os.path.join(out_sections, name + '.jsx'), 'w').write(HEAD + f"export default function {name}({{ v }}) {{\n  return (\n    <>\n{jsx}\n    </>\n  );\n}}\n")

# The logic class
s_a = find(r'^<script type="text/x-dc" data-dc-script') + 1
s_b = find(r'^</script>', s_a) - 1
code = L(s_a, s_b)
code = code.replace('class Component extends DCLogic {', "export default class Component extends BaseVM {", 1)
code = code.replace('  _go(p) { location.hash = p; }', '  _go(p) { this.navigate(p); }')
code = rootify(code)
open(os.path.join(ROOT, 'src/legacy/vm.js'), 'w').write(
    "// Generated by tools/port_legacy.py: the original site's logic, unchanged except navigation.\n/* eslint-disable */\n"
    "import BaseVM from './BaseVM';\n\n" + code + '\n')

open(os.path.join(ROOT, 'src/legacy/hover.css'), 'w').write('/* Hover states for ported sections (generated) */\n' + '\n'.join(sorted(all_hover)) + '\n')
print('sections:', len(SECTIONS), 'hover rules:', len(all_hover), 'logic lines:', s_b - s_a + 1)
